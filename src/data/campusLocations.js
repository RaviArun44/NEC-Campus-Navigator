// Helper: get distance between any two building IDs
export function getDistance(fromId, toId) {
  if (fromId === toId) return 0;
  const key1 = `${fromId}|${toId}`;
  const key2 = `${toId}|${fromId}`;
  return distances[key1] ?? distances[key2] ?? null;
}

// Walking speed: ~80 meters per minute
export function getWalkingTime(meters) {
  return Math.ceil(meters / 80);
}

